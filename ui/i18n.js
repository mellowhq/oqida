function setLang(l) { LANG = I18N[l] ? l : "en"; document.documentElement.lang = LANG; }
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
  if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
  return s;
}
